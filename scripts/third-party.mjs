// Writes THIRD-PARTY-NOTICES.md: every Rust crate compiled into the Windows build (cargo metadata, x64 target)
// and every production npm package bundled into the UI, with its licence, plus fonts, icons and NSIS.
// Run: node scripts/third-party.mjs   (after cargo fetch + pnpm install)
import { execSync } from "node:child_process";
import fs from "node:fs";

const meta = JSON.parse(execSync("cargo metadata --format-version 1 --locked --filter-platform x86_64-pc-windows-msvc", { maxBuffer: 1 << 28 }).toString());
const ours = new Set(["galaxy-download-manager", "gdm-core", "gdm-bridge", "gdm-fixture"]);
const pkgs = new Map(meta.packages.map((p) => [p.id, p]));
const reach = new Set();
const nodes = new Map(meta.resolve.nodes.map((n) => [n.id, n]));
const walk = (id) => {
  if (reach.has(id)) return;
  reach.add(id);
  for (const d of nodes.get(id)?.deps ?? []) if (d.dep_kinds.some((k) => k.kind !== "dev" && k.kind !== "build")) walk(d.pkg);
};
for (const p of meta.packages) if (p.name === "galaxy-download-manager" || p.name === "gdm-bridge") walk(p.id);
const crates = [...reach].map((id) => pkgs.get(id)).filter((p) => !ours.has(p.name)).sort((a, b) => a.name.localeCompare(b.name));

const npm = JSON.parse(execSync("pnpm licenses list --prod --json").toString());
const npmRows = Object.entries(npm).flatMap(([lic, list]) => list.map((p) => [p.name, p.versions.join(", "), lic, p.homepage ?? ""])).sort((a, b) => a[0].localeCompare(b[0]));

let md = `# Third-party notices

Galaxy Download Manager is © GoldenIQ under RPL-1.5 (see LICENSE). It includes the third-party components below,
each under its own licence. Full licence texts are in each package's source (crates.io / npm) and, for the fonts,
in \`public/fonts/OFL-*.txt\`. Generated by \`node scripts/third-party.mjs\`; do not edit by hand.

## Bundled assets

| Component | Version | Licence | Source |
|---|---|---|---|
| Kantumruy Pro (Khmer font) | Fontsource 5.3.0 | OFL-1.1 | https://fonts.google.com/specimen/Kantumruy+Pro |
| Outfit (Latin font) | Fontsource 5.3.0 | OFL-1.1 | https://fonts.google.com/specimen/Outfit |
| JetBrains Mono | Fontsource 5.3.0 | OFL-1.1 | https://www.jetbrains.com/lp/mono/ |
| Phosphor Icons (path data) | 2.1.1 | MIT | https://phosphoricons.com |
| NSIS (installer), Khmer.nlf / Khmer.nsh derived from NSIS English files | 3.11 | zlib | https://nsis.sourceforge.io |

## npm packages in the user interface (${npmRows.length})

| Package | Version | Licence | Homepage |
|---|---|---|---|
${npmRows.map((r) => `| ${r.join(" | ")} |`).join("\n")}

## Rust crates in gdm.exe and gdm-bridge.exe (${crates.length})

| Crate | Version | Licence | Repository |
|---|---|---|---|
${crates.map((p) => `| ${p.name} | ${p.version} | ${p.license ?? "see " + (p.license_file ?? "crate")} | ${p.repository ?? ""} |`).join("\n")}
`;
fs.writeFileSync("THIRD-PARTY-NOTICES.md", md);
console.log(`THIRD-PARTY-NOTICES.md: ${crates.length} crates, ${npmRows.length} npm packages`);
